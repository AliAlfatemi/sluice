"""Generate LaTeX macros for RQ1's headline numbers directly from the raw
results JSON `rq1_expanded.py` produces -- so the paper's numbers are
regenerated from the archived evidence, not manually transcribed.

Usage: python3 generate_rq1_macros.py rq1_expanded_final_results.json \
           --output rq1_macros.tex
"""
from __future__ import annotations

import argparse
import json
from pathlib import Path
from typing import Any


def _frac(entry: dict[str, Any]) -> str:
    return f"{entry['successes']}/{entry['total']}"


def build_macros(result: dict[str, Any]) -> str:
    m = result["metrics"]
    workload = result["workload"]
    lines = [
        "% Auto-generated by generate_rq1_macros.py from a raw RQ1 results",
        "% JSON. Do not hand-edit; regenerate instead.",
        f"\\newcommand{{\\rqOneNCases}}{{{workload['n_cases']}}}",
        f"\\newcommand{{\\rqOneNAttacks}}{{{workload['n_attack_cases']}}}",
        f"\\newcommand{{\\rqOneNControls}}{{{workload['n_control_cases']}}}",
        f"\\newcommand{{\\rqOneUndefendedAttackSuccess}}{{{_frac(m['undefended']['attack_success'])}}}",
        f"\\newcommand{{\\rqOneSluiceAttackSuccess}}{{{_frac(m['sluice']['attack_success'])}}}",
        f"\\newcommand{{\\rqOneUndefendedOverallCompletion}}{{{_frac(m['undefended']['overall_task_completion'])}}}",
        f"\\newcommand{{\\rqOneSluiceOverallCompletion}}{{{_frac(m['sluice']['overall_task_completion'])}}}",
        f"\\newcommand{{\\rqOneSluiceCleanCompletion}}{{{_frac(m['sluice']['clean_task_completion'])}}}",
        f"\\newcommand{{\\rqOneSluiceAttackedCompletion}}{{{_frac(m['sluice']['attacked_task_completion'])}}}",
        f"\\newcommand{{\\rqOneUndefendedAttackedCompletion}}{{{_frac(m['undefended']['attacked_task_completion'])}}}",
    ]
    return "\n".join(lines) + "\n"


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("results_json", type=Path)
    parser.add_argument("--output", type=Path, default=Path("rq1_macros.tex"))
    args = parser.parse_args(argv)

    result = json.loads(args.results_json.read_text(encoding="utf-8"))
    if result.get("experiment_id") != "rq1_expanded":
        raise SystemExit(
            f"refusing to generate macros from unexpected experiment_id "
            f"{result.get('experiment_id')!r}; expected 'rq1_expanded'"
        )
    if len(result["cases"]) != 25:
        raise SystemExit(f"expected 25 cases in the archive, found {len(result['cases'])}")

    macros = build_macros(result)
    args.output.write_text(macros, encoding="utf-8")
    print(macros, end="")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
